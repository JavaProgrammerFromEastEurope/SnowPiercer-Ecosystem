#!/usr/bin/env python3
"""Validate and aggregate run_stage_matrix.sh summary.tsv files."""
from __future__ import annotations

import argparse
import csv
import json
import sys
from collections import Counter
from pathlib import Path

EXPECTED_HEADER = ["stage", "status", "exit_code", "seconds", "log"]
VALID_STATUSES = {"PASS", "FAIL", "TIMEOUT"}


class SummaryError(ValueError):
    pass


def summarize(path: Path, check_logs: bool = False) -> dict:
    if not path.is_file():
        raise SummaryError(f"summary file does not exist: {path}")
    rows = []
    seen_stages = set()
    with path.open("r", encoding="utf-8", newline="") as handle:
        reader = csv.DictReader(handle, delimiter="\t")
        if reader.fieldnames != EXPECTED_HEADER:
            raise SummaryError(f"invalid header; expected: {' '.join(EXPECTED_HEADER)}")
        for line_number, row in enumerate(reader, start=2):
            if None in row or any(row.get(key) is None for key in EXPECTED_HEADER):
                raise SummaryError(f"malformed row at line {line_number}")
            try:
                stage = int(row["stage"])
                code = int(row["exit_code"])
                seconds = int(row["seconds"])
            except ValueError as exc:
                raise SummaryError(f"non-integer stage/exit_code/seconds at line {line_number}") from exc
            if stage < 1 or seconds < 0:
                raise SummaryError(f"invalid stage or duration at line {line_number}")
            if stage in seen_stages:
                raise SummaryError(f"duplicate stage {stage}")
            seen_stages.add(stage)
            status = row["status"]
            if status not in VALID_STATUSES:
                raise SummaryError(f"invalid status {status!r} at line {line_number}")
            if status == "PASS" and code != 0:
                raise SummaryError(f"PASS stage {stage} has non-zero exit code")
            if status == "FAIL" and code == 0:
                raise SummaryError(f"FAIL stage {stage} has zero exit code")
            if status == "TIMEOUT" and code not in (124, 137):
                raise SummaryError(f"TIMEOUT stage {stage} has unexpected exit code {code}")
            log = row["log"]
            if not log or Path(log).name != log:
                raise SummaryError(f"invalid log filename at line {line_number}")
            if check_logs and not (path.parent / log).is_file():
                raise SummaryError(f"missing log file for stage {stage}: {log}")
            rows.append({"stage": stage, "status": status, "exit_code": code,
                         "seconds": seconds, "log": log})
    if not rows:
        raise SummaryError("summary contains no stage results")
    counts = Counter(row["status"] for row in rows)
    return {
        "source": path.name,
        "stage_count": len(rows),
        "counts": {status: counts.get(status, 0) for status in ("PASS", "FAIL", "TIMEOUT")},
        "total_seconds": sum(row["seconds"] for row in rows),
        "successful": all(row["status"] == "PASS" for row in rows),
        "stages": rows,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("summary", type=Path, help="summary.tsv generated by run_stage_matrix.sh")
    parser.add_argument("--check-logs", action="store_true", help="require every referenced log file")
    parser.add_argument("--json", dest="json_path", type=Path, help="write JSON report to this path")
    args = parser.parse_args()
    try:
        report = summarize(args.summary, check_logs=args.check_logs)
    except (OSError, SummaryError, csv.Error) as exc:
        print(f"summary error: {exc}", file=sys.stderr)
        return 2
    encoded = json.dumps(report, indent=2, sort_keys=True) + "\n"
    if args.json_path:
        args.json_path.parent.mkdir(parents=True, exist_ok=True)
        args.json_path.write_text(encoded, encoding="utf-8")
    print(f"Stages: {report['stage_count']} | PASS: {report['counts']['PASS']} | "
          f"FAIL: {report['counts']['FAIL']} | TIMEOUT: {report['counts']['TIMEOUT']} | "
          f"seconds: {report['total_seconds']}")
    if args.json_path:
        print(f"JSON report: {args.json_path}")
    return 0 if report["successful"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
