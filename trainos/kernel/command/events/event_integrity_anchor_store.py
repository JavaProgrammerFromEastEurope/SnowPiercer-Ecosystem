from __future__ import annotations

import sqlite3
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from threading import RLock
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from .command_event_store import CommandEventStore


@dataclass(frozen=True, slots=True)
class EventIntegrityAnchor:
    """A trusted reference to one exact event-log chain head."""

    anchor_id: int
    event_sequence: int
    event_hash: str
    created_at: datetime


class EventIntegrityAnchorStore:
    """Persistent chain-head anchors, intended for a separately controlled database.

    This store provides a comparison point for detecting event-log rollback or edits
    after an anchor was recorded. It is not independently tamper-proof: deployments
    must protect this database separately or export anchors to remote/WORM storage.
    """

    def __init__(self, database_path: str | Path) -> None:
        if not isinstance(database_path, (str, Path)) or not str(database_path).strip():
            raise ValueError("database_path must not be empty")
        self._database_path = str(database_path)
        self._lock = RLock()
        self._connection = sqlite3.connect(self._database_path, check_same_thread=False)
        try:
            self._connection.row_factory = sqlite3.Row
            with self._lock, self._connection:
                self._connection.execute("PRAGMA foreign_keys = ON")
                self._connection.execute("""CREATE TABLE IF NOT EXISTS event_integrity_anchors (
                    anchor_id INTEGER PRIMARY KEY AUTOINCREMENT,
                    event_sequence INTEGER NOT NULL CHECK(event_sequence >= 0),
                    event_hash TEXT NOT NULL,
                    created_at TEXT NOT NULL
                )""")
                self._connection.execute(
                    "CREATE INDEX IF NOT EXISTS idx_event_integrity_anchors_sequence "
                    "ON event_integrity_anchors(event_sequence, anchor_id)"
                )

        except BaseException:
            self._connection.close()
            raise

    @property
    def database_path(self) -> str:
        return self._database_path

    def create_anchor(self, event_store: CommandEventStore) -> EventIntegrityAnchor:
        from .command_event_store import CommandEventStore
        if not isinstance(event_store, CommandEventStore):
            raise TypeError("event_store must be a CommandEventStore")
        integrity_findings, (sequence, event_hash), _ = event_store.integrity_snapshot()
        if integrity_findings:
            raise ValueError("cannot anchor an event store with integrity findings")
        if len(event_hash) != 64:
            raise ValueError("event store head has no valid SHA-256 hash")
        created_at = datetime.now(timezone.utc)
        with self._lock, self._connection:
            latest_row = self._connection.execute(
                "SELECT anchor_id, event_sequence, event_hash, created_at "
                "FROM event_integrity_anchors ORDER BY anchor_id DESC LIMIT 1"
            ).fetchone()
            if latest_row is not None:
                latest = self._from_row(latest_row)
                if sequence < latest.event_sequence:
                    raise ValueError("event store head is older than the latest trusted anchor")
                if sequence == latest.event_sequence:
                    if event_hash != latest.event_hash:
                        raise ValueError("event store head conflicts with the latest trusted anchor")
                    return latest
            cursor = self._connection.execute(
                "INSERT INTO event_integrity_anchors(event_sequence, event_hash, created_at) VALUES (?, ?, ?)",
                (sequence, event_hash, created_at.isoformat()),
            )
            anchor_id = int(cursor.lastrowid)
        return EventIntegrityAnchor(anchor_id, sequence, event_hash, created_at)

    def import_signed_anchor(self, serialized: str, signing_key: bytes) -> EventIntegrityAnchor:
        """Verify and persist a signed portable anchor without permitting rollback.

        The local anchor ID is generated by this store; the signed source anchor ID
        remains authenticated in the imported envelope but is not used as a local key.
        """
        from .signed_event_integrity_anchor import verify_signed_event_integrity_anchor

        imported = verify_signed_event_integrity_anchor(serialized, signing_key)
        with self._lock, self._connection:
            latest_row = self._connection.execute(
                "SELECT anchor_id, event_sequence, event_hash, created_at "
                "FROM event_integrity_anchors ORDER BY anchor_id DESC LIMIT 1"
            ).fetchone()
            if latest_row is not None:
                latest = self._from_row(latest_row)
                if imported.event_sequence < latest.event_sequence:
                    raise ValueError("imported anchor would roll back the latest trusted sequence")
                if imported.event_sequence == latest.event_sequence:
                    if imported.event_hash != latest.event_hash:
                        raise ValueError("imported anchor conflicts with the latest trusted anchor")
                    return latest
            cursor = self._connection.execute(
                "INSERT INTO event_integrity_anchors(event_sequence, event_hash, created_at) VALUES (?, ?, ?)",
                (imported.event_sequence, imported.event_hash, imported.created_at.isoformat()),
            )
            anchor_id = int(cursor.lastrowid)
        return EventIntegrityAnchor(anchor_id, imported.event_sequence,
                                    imported.event_hash, imported.created_at)

    @staticmethod
    def _from_row(row: sqlite3.Row) -> EventIntegrityAnchor:
        return EventIntegrityAnchor(
            anchor_id=int(row["anchor_id"]),
            event_sequence=int(row["event_sequence"]),
            event_hash=str(row["event_hash"]),
            created_at=datetime.fromisoformat(row["created_at"]),
        )

    def latest(self) -> EventIntegrityAnchor | None:
        with self._lock:
            row = self._connection.execute(
                "SELECT anchor_id, event_sequence, event_hash, created_at "
                "FROM event_integrity_anchors ORDER BY anchor_id DESC LIMIT 1"
            ).fetchone()
        return None if row is None else self._from_row(row)

    def all_anchors(self) -> tuple[EventIntegrityAnchor, ...]:
        with self._lock:
            rows = self._connection.execute(
                "SELECT anchor_id, event_sequence, event_hash, created_at "
                "FROM event_integrity_anchors ORDER BY anchor_id"
            ).fetchall()
        return tuple(self._from_row(row) for row in rows)

    def verify_against(
        self,
        event_store: CommandEventStore,
        *,
        anchor: EventIntegrityAnchor | None = None,
        integrity_snapshot: tuple[tuple[dict[str, object], ...], tuple[int, str], dict[int, str | None]] | None = None,
    ) -> tuple[dict[str, object], ...]:
        """Compare one anchor with one consistent event-log snapshot.

        Optional snapshot arguments let the recovery gate reuse the exact evidence
        used to build its assessment instead of independently re-reading the log.
        """
        from .command_event_store import CommandEventStore
        if not isinstance(event_store, CommandEventStore):
            raise TypeError("event_store must be a CommandEventStore")
        if anchor is not None and not isinstance(anchor, EventIntegrityAnchor):
            raise TypeError("anchor must be an EventIntegrityAnchor or None")
        if integrity_snapshot is None:
            integrity_snapshot = event_store.integrity_snapshot()
        integrity_findings, (head_sequence, head_hash), hashes = integrity_snapshot
        findings: list[dict[str, object]] = [
            {**finding, "code": "event_store_integrity_failure", "integrity_code": finding["code"]}
            for finding in integrity_findings
        ]
        if anchor is None:
            anchor = self.latest()
        if anchor is None:
            findings.append({"code": "anchor_missing"})
            return tuple(findings)
        if anchor.event_sequence == 0:
            if head_sequence == 0 and head_hash == anchor.event_hash:
                return tuple(findings)
            findings.append({"code": "anchored_empty_log_changed", "anchor_id": anchor.anchor_id,
                             "anchored_sequence": 0, "current_sequence": head_sequence})
            return tuple(findings)
        stored_hash = hashes.get(anchor.event_sequence)
        if stored_hash is None:
            code = "anchored_tail_missing" if head_sequence < anchor.event_sequence else "anchor_sequence_missing"
            findings.append({"code": code, "anchor_id": anchor.anchor_id,
                             "anchored_sequence": anchor.event_sequence, "current_sequence": head_sequence})
            return tuple(findings)
        if stored_hash != anchor.event_hash:
            findings.append({"code": "anchor_hash_mismatch", "anchor_id": anchor.anchor_id,
                             "anchored_sequence": anchor.event_sequence})
        return tuple(findings)

    def close(self) -> None:
        with self._lock:
            self._connection.close()
